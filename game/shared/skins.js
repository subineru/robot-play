export function getSkinById(skinId) {
  return MECHA_SKINS.find((s) => s.id === skinId) || MECHA_SKINS[0];
}

/**
 * Combine base preset with optional 5-channel custom DIY overrides.
 */
export function resolveEffectivePalette(skinId = 'SKIN-01', customPalette = null) {
  const base = getSkinById(skinId);
  if (!customPalette) {
    return { ...base };
  }
  return {
    ...base,
    primary: customPalette.primary || base.primary,
    secondary: customPalette.secondary || base.secondary,
    frame: customPalette.frame || base.frame,
    sensor: customPalette.sensor || base.sensor,
    thruster: customPalette.thruster || base.thruster,
    saber: customPalette.saber || base.saber,
  };
}
